    private val entries: Map<String, String> by lazy { build() }
    private val exact: Set<String> by lazy { entries.keys.filter { it.length < 4 }.toSet() }
    private val stems: List<Pair<String, String>> by lazy {
        entries.filter { it.key.length >= 4 }.toList().sortedByDescending { it.first.length }
    }

    fun forWord(word: String): String? {
        val w = word.lowercase(Locale.ROOT).trim().trim('.', ',', '!', '?', ':', ';', '"', '\'', '(', ')', '„', '“')
            .replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss")
        if (w.isEmpty()) return null
        entries[w]?.let { return it }
        if (w in exact) return entries[w]
        for ((stem, emoji) in stems) if (w.startsWith(stem)) return emoji
        return null
    }

    private fun MutableMap<String, String>.add(emoji: String, vararg words: String) {
        words.forEach { this[it.lowercase(Locale.ROOT).replace("ä", "ae").replace("ö", "oe").replace("ü", "ue").replace("ß", "ss")] = emoji }
    }

