 * Wörterbuch Wort → Emoji (Deutsch/Englisch). Einträge sind Wortstämme; ein Wort trifft,
 * wenn es (klein geschrieben, ohne Satzzeichen) exakt gleich ist oder mit dem Stamm beginnt.
